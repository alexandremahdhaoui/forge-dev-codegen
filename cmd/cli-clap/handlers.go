package main

import (
	"bytes"
	"context"
	"fmt"
	"text/template"

	"github.com/alexandremahdhaoui/forge-dev-codegen/internal/surface"
)

// NewHandlers wires the generate tool: the model's surface.commands decide
// the subcommands, clap does the dispatch. The emitted module keeps the
// cli cell's behavior contract - raw args to the handler, exit codes pass
// through, an unknown command exits 2 naming itself.
func NewHandlers() Handlers {
	return Handlers{
		Generate: func(_ context.Context, input GenerateInput) (*GenerateOutput, error) {
			if input.Kind != "cli" {
				return nil, fmt.Errorf("emitting %q: cli-clap fills the cli cell only", input.Kind)
			}

			if input.Language != "rust" {
				return nil, fmt.Errorf("emitting for %q: cli-clap generates rust only", input.Language)
			}

			commands, err := surface.Commands(input.Surface)
			if err != nil {
				return nil, fmt.Errorf("reading surface.commands for %q: %w", input.Name, err)
			}

			var buf bytes.Buffer
			if err := clapTmpl.Execute(&buf, map[string]any{
				"Name":        input.Name,
				"Version":     input.Version,
				"Description": input.Description,
				"Checksum":    input.Checksum,
				"Commands":    commands,
			}); err != nil {
				return nil, fmt.Errorf("rendering the clap dispatcher for %q: %w", input.Name, err)
			}

			return &GenerateOutput{
				Files: []GeneratedFile{{Path: "zz_generated_cli.rs", Content: buf.String()}},
			}, nil
		},
	}
}

var clapTmpl = template.Must(template.New("clap").Parse(`// Code generated by cli-clap (forge-dev-codegen). DO NOT EDIT.
// Source: forge-dev.yaml
// SourceChecksum: {{ .Checksum }}

//! {{ .Name }} v{{ .Version }}: a cli kind program dispatched by clap. The
//! author writes new_cli_handlers() beside this module; the behavior
//! contract is every cli cell's - raw args to the handler, exit codes pass
//! through, an unknown command exits 2 naming itself.

#![allow(dead_code)]

/// One handler per declared command. The type makes every field required.
pub struct CLIHandlers {
{{- range .Commands }}
    /// Runs the {{ .Name }} command. {{ .Description }}
    pub {{ .SnakeName }}: fn(&[String]) -> i32,
{{- end }}
}

/// dispatch routes args through clap and answers the process exit code.
/// Flag parsing is left to the handler: every subcommand takes its args
/// raw, exactly as the builtin cell hands them over.
pub fn dispatch(handlers: CLIHandlers, args: &[String]) -> i32 {
    let command = clap::Command::new("{{ .Name }}")
        .about("{{ .Description }}")
        .version("{{ .Version }}")
        .disable_help_subcommand(true){{ range .Commands }}
        .subcommand(
            clap::Command::new("{{ .Name }}")
                .about("{{ .Description }}")
                .arg(
                    clap::Arg::new("args")
                        .num_args(0..)
                        .allow_hyphen_values(true)
                        .trailing_var_arg(true),
                ),
        ){{ end }};

    let mut argv = vec!["{{ .Name }}".to_string()];
    argv.extend_from_slice(args);

    let matches = match command.try_get_matches_from(argv) {
        Ok(matches) => matches,
        Err(err) => {
            if err.kind() == clap::error::ErrorKind::InvalidSubcommand {
                if let Some(clap::error::ContextValue::String(name)) =
                    err.get(clap::error::ContextKind::InvalidSubcommand)
                {
                    eprintln!("{{ .Name }}: unknown command {name:?}");
                    return 2;
                }
            }

            let _ = err.print();
            return 2;
        }
    };

    match matches.subcommand() {
{{- range .Commands }}
        Some(("{{ .Name }}", sub)) => {
            let command_args: Vec<String> = sub
                .get_many::<String>("args")
                .map(|values| values.cloned().collect())
                .unwrap_or_default();

            (handlers.{{ .SnakeName }})(&command_args)
        }
{{- end }}
        _ => {
            eprintln!("{{ .Name }}: a command is required");
            2
        }
    }
}
`))
