func Detailed(owner string) []Member {
	out := make([]Member, 0, len(detailed))

	for _, m := range detailed {
		m.Display = strings.ReplaceAll(m.Display, OwnerSlot, owner)
		out = append(out, m)
	}

	return out
}

func Runtime(owner string) Member {
	m := runtime
	m.Display = strings.ReplaceAll(m.Display, OwnerSlot, owner)

	return m
}

func All(owner string) []Member {
	return append([]Member{Runtime(owner)}, Detailed(owner)...)
}

func WireRuntime() WireMember {
	return wire[0]
}

func WireDetailed() []WireMember {
	return append([]WireMember(nil), wire[1:]...)
}

func ByVariant(variant string) (Member, bool) {
	for _, m := range All("") {
		if m.Variant == variant {
			return m, true
		}
	}

	return Member{}, false
}

func ByRestStatus(status int) (Member, bool) {
	for _, m := range detailed {
		if m.RestStatus != 0 && m.RestStatus == status {
			return m, true
		}
	}

	return Member{}, false
}

func Invalid() Member {
	m, _ := ByVariant("Invalid")

	return m
}

func VariantNames() []string {
	out := make([]string, 0, len(detailed)+1)
	for _, m := range All("") {
		out = append(out, m.Variant)
	}

	sort.Strings(out)

	return out
}

func DetailedVariantNames() []string {
	out := make([]string, 0, len(detailed))
	for _, m := range detailed {
		out = append(out, m.Variant)
	}

	sort.Strings(out)

	return out
}

func RestStatusList() string {
	parts := make([]string, 0, len(detailed))

	for _, m := range detailed {
		if m.RestStatus == 0 {
			parts = append(parts, m.Variant+" (the operation's invalid status)")

			continue
		}

		parts = append(parts, fmt.Sprintf("%s (%d)", m.Variant, m.RestStatus))
	}

	return strings.Join(parts, ", ")
}
