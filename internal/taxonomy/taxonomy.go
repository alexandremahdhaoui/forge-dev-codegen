const OwnerSlot = "{owner}"

const VectorFiller = "generated by vectors-rust"

type Field struct {
	Name string
	Type string
}

type Member struct {
	Variant        string
	Fields         []Field
	Display        string
	Wire           string
	RestStatus     int
	RestStatusExpr string
	GrpcMethod     string
	GrpcCode       string
	Generic        bool
}

func (m Member) FieldList() string {
	parts := make([]string, 0, len(m.Fields))
	for _, f := range m.Fields {
		parts = append(parts, f.Name+": "+f.Type)
	}

	return strings.Join(parts, ", ")
}

func (m Member) Literal(errorType, subject, filler string) string {
	parts := make([]string, 0, len(m.Fields))

	for i, f := range m.Fields {
		value := filler
		if i == 0 {
			value = subject
		}

		parts = append(parts, fmt.Sprintf("%s: %q.to_string()", f.Name, value))
	}

	return fmt.Sprintf("%s::%s { %s }", errorType, m.Variant, strings.Join(parts, ", "))
}

func (m Member) DetailExpr() string {
	if m.Generic {
		return `"internal error".to_string()`
	}

	return "error.to_string()"
}

