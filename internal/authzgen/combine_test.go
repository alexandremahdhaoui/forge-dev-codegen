func writeManifestCell(t *testing.T, root, dir, manifest string) {
	t.Helper()

	cell := filepath.Join(root, dir)

	if err := os.MkdirAll(cell, 0o755); err != nil {
		t.Fatalf("making the cell %s: %v", dir, err)
	}

	if err := os.WriteFile(filepath.Join(cell, "zz_generated_authz.json"), []byte(manifest), 0o600); err != nil {
		t.Fatalf("writing the manifest of %s: %v", dir, err)
	}
}

func TestTwoModulesOnDifferentSchemasAreRefusedNamingBothSchemas(t *testing.T) {
	root := twoCells(t)

	writeManifestCell(t, root, "old", `{
  "module": "old",
  "schema": "1.1",
  "model": "zz_generated_old.fga",
  "tests": "zz_generated_old.fga.yaml",
  "types": [],
  "references": [],
  "extends": [],
  "cases": []
}
`)

	if err := os.WriteFile(filepath.Join(root, "old", "zz_generated_old.fga"), []byte("module old\n"), 0o600); err != nil {
		t.Fatalf("writing the old module: %v", err)
	}

	if err := os.WriteFile(filepath.Join(root, "old", "zz_generated_old.fga.yaml"), []byte("name: \"old\"\ntests:\n"), 0o600); err != nil {
		t.Fatalf("writing the old tests: %v", err)
	}

	refusedCombination(t, root, []string{
		"../session/zz_generated_authz.json",
		"../old/zz_generated_authz.json",
	}, `module "session" writes schema "1.2" and module "old" writes schema "1.1"`, "one model holds one schema")
}

