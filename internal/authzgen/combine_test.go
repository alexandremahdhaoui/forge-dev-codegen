func writeModuleCell(t *testing.T, root, dir, doc string) {
	t.Helper()

	cell := filepath.Join(root, dir)

	if err := os.MkdirAll(cell, 0o755); err != nil {
		t.Fatalf("making the cell %s: %v", dir, err)
	}

	files, err := authzgen.Generate([]byte(doc))
	if err != nil {
		t.Fatalf("generating the module of %s: %v", dir, err)
	}

	for _, f := range files {
		if err := os.WriteFile(filepath.Join(cell, f.Path), []byte(f.Content), 0o600); err != nil {
			t.Fatalf("writing %s of %s: %v", f.Path, dir, err)
		}
	}
}

const chatSpec = `module: chat
references:
  - module: session
    types:
      - name: character
      - name: session
        relations: [member]
types:
  - name: channel
    relations:
      - name: session
        subjects: [session]
      - name: member
        expression: member from session
      - name: post
        expression: member
vectors:
  - name: a member may post
    tuples:
      - user: session:s1
        relation: session
        object: channel:c1
      - user: character:alice
        relation: member
        object: session:s1
    checks:
      - user: character:alice
        relation: post
        object: channel:c1
        expected: true
`

func twoCells(t *testing.T) string {
	t.Helper()

	root := t.TempDir()

	writeModuleCell(t, root, "session", sessionSpec+`vectors:
  - name: a member may join
    tuples:
      - user: character:alice
        relation: member
        object: session:s1
    checks:
      - user: character:alice
        relation: join
        object: session:s1
        expected: true
`)
	writeModuleCell(t, root, "chat", chatSpec)

	if err := os.MkdirAll(filepath.Join(root, "combined"), 0o755); err != nil {
		t.Fatalf("making the combine cell: %v", err)
	}

	return root
}

func combine(t *testing.T, root string, modules ...string) map[string]string {
	t.Helper()

	files, err := authzgen.Combine(authzgen.CombineOptions{
		Name:    "songe-authz",
		SrcDir:  filepath.Join(root, "combined"),
		Modules: modules,
	})
	if err != nil {
		t.Fatalf("combining: %v", err)
	}

	byPath := map[string]string{}
	for _, f := range files {
		byPath[f.Path] = f.Content
	}

	return byPath
}

func refusedCombination(t *testing.T, root string, modules []string, wants ...string) {
	t.Helper()

	_, err := authzgen.Combine(authzgen.CombineOptions{
		Name:    "songe-authz",
		SrcDir:  filepath.Join(root, "combined"),
		Modules: modules,
	})
	if err == nil {
		t.Fatal("the combination was accepted")
	}

	for _, want := range wants {
		if !strings.Contains(err.Error(), want) {
			t.Fatalf("the refusal %q never named %q", err, want)
		}
	}
}

func TestTheCombinationWritesTheModFileTheMergedTestsAndACopyOfEveryModule(t *testing.T) {
	root := twoCells(t)
	files := combine(t, root, "../session/zz_generated_authz.json", "../chat/zz_generated_authz.json")

	for _, path := range []string{
		"zz_generated_fga.mod",
		"zz_generated_fga.yaml",
		"zz_generated_session.fga",
		"zz_generated_chat.fga",
	} {
		if _, written := files[path]; !written {
			t.Errorf("the combination never wrote %s", path)
		}
	}

	if len(files) != 4 {
		t.Fatalf("the combination wrote %d files", len(files))
	}
}

