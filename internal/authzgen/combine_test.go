func TestTheCombinedDemoRegeneratesExactlyTheCommittedGoldenFiles(t *testing.T) {
	cell := filepath.Join(demoDir, "combined")

	spec, err := os.ReadFile(filepath.Join(cell, "combine.yaml"))
	if err != nil {
		t.Fatalf("reading the demo combine.yaml: %v", err)
	}

	modules, err := authzgen.ModulesFromSpec(spec)
	if err != nil {
		t.Fatalf("reading the demo combine.yaml: %v", err)
	}

	files, err := authzgen.Combine(authzgen.CombineOptions{
		Name:    "demo-authz-combined",
		SrcDir:  cell,
		Modules: modules,
	})
	if err != nil {
		t.Fatalf("combining the demo: %v", err)
	}

	for _, f := range files {
		want, err := os.ReadFile(filepath.Join(cell, f.Path))
		if err != nil {
			t.Fatalf("reading the demo file %s: %v", f.Path, err)
		}

		if f.Content != string(want) {
			t.Errorf("combined/%s drifted from the committed golden file\n got:\n%s\nwant:\n%s", f.Path, f.Content, want)
		}
	}
}

func TestThePerModuleTestFileNamesTheModFileTheCombineKindWrites(t *testing.T) {
	root := twoCells(t)

	module, err := os.ReadFile(filepath.Join(root, "chat", "zz_generated_chat.fga.yaml"))
	if err != nil {
		t.Fatalf("reading the chat tests: %v", err)
	}

	named := ""

	for _, line := range strings.Split(string(module), "\n") {
		if rest, cut := strings.CutPrefix(line, "model_file: "); cut {
			named = strings.Trim(rest, `"`)
		}
	}

	if named == "" {
		t.Fatalf("the chat tests name no model_file\n%s", module)
	}

	files := combine(t, root, "../session/zz_generated_authz.json", "../chat/zz_generated_authz.json")

	if _, written := files[named]; !written {
		t.Fatalf("the module tests name %q, which the combination never writes", named)
	}
}

