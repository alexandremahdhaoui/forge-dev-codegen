const header = "// Code generated by vectors-rust (forge-dev-codegen). DO NOT EDIT."

type Options struct {
	Service  string
	CrateDir string
	Cell     string
	Proto    []byte
}

type File struct {
	Path    string
	Content string
}

var serviceIdent = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

func Generate(openapiDoc, vectorsDoc []byte, opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the vectors: the service name is required")
	}

	if !serviceIdent.MatchString(hexrust.Snake(opts.Service)) {
		return nil, fmt.Errorf("emitting the vectors: service name %q is not one Rust or Cargo can spell, use letters, digits and underscores and start with a letter", opts.Service)
	}

	if opts.Cell == "" {
		opts.Cell = udprust.DefaultCell
	}

	spec, err := hexrust.Parse(openapiDoc)
	if err != nil {
		return nil, err
	}

	datagrams, err := readDatagramService(opts.Proto, opts.Cell)
	if err != nil {
		return nil, err
	}

	vectors, err := parseVectors(vectorsDoc, declaredOperations(spec), declaredDatagrams(datagrams))
	if err != nil {
		return nil, err
	}

	v, err := buildView(spec, vectors, datagrams, opts)
	if err != nil {
		return nil, err
	}

	content, err := render("file", v)
	if err != nil {
		return nil, err
	}

	return []File{
		{
			Path:    path.Join(opts.CrateDir, "tests", "zz_generated_vectors.rs"),
			Content: content,
		},
	}, nil
}

func declaredOperations(spec *hexrust.Spec) func(string) bool {
	declared := map[string]bool{}

	for _, c := range spec.Controllers {
		for _, op := range c.Operations {
			declared[op.ID] = true
		}
	}

	return func(id string) bool { return declared[id] }
}

func declaredDatagrams(svc *datagramService) func(string) bool {
	if svc == nil {
		return func(string) bool { return false }
	}

	return func(operation string) bool {
		_, ok := svc.Rpcs[operation]

		return ok
	}
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

