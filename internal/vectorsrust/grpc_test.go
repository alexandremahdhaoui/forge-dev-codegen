const callProto = `syntax = "proto3";

package songe.hello.v1;

service Hello {
  rpc Ping(PingRequest) returns (PingReply);
}

message PingRequest {
  string message = 1;
  uint64 count = 2;
}

message PingReply {
  string message = 1;
  uint64 count = 2;
}
`

const callCases = `{
  "cases": [
    {
      "case": "grpc_ping_answers_the_count_raised_by_one",
      "operation": "grpc_Ping",
      "input": { "message": "songe", "count": 7 },
      "controllerReply": { "message": "songe", "count": 8 }
    },
    {
      "case": "grpc_ping_with_an_empty_message_is_refused",
      "operation": "grpc_Ping",
      "input": { "message": "", "count": 0 },
      "expectedErrorSubstring": "message"
    }
  ]
}`

func callOptions() vectorsrust.Options {
	return vectorsrust.Options{
		Service:   "songe-hello",
		GrpcProto: []byte(callProto),
		GrpcCell:  "grpc",
	}
}

func generateCalls(t *testing.T, cases string) string {
	t.Helper()

	files, err := vectorsrust.Generate([]byte(helloSpec), []byte(cases), callOptions())
	if err != nil {
		t.Fatalf("generating: %v", err)
	}

	return files[0].Content
}

