func TestAGrpcCaseIsRefusedWhenItNamesAnUnknownRpcOrCarriesHttpFields(t *testing.T) {
	tests := []struct {
		name string
		body string
		want string
	}{
		{
			name: "an rpc the proto never declares",
			body: `{"case": "c", "operation": "grpc_Pong", "controllerReply": {}}`,
			want: `operation "grpc_Pong" names no operationId of the OpenAPI document, no udp_<rpc> of the datagram service and no grpc_<Rpc> of the grpc service`,
		},
		{
			name: "neither a reply nor a substring",
			body: `{"case": "c", "operation": "grpc_Ping", "input": {"message": "songe"}}`,
			want: `a grpc case needs controllerReply`,
		},
		{
			name: "a reply and a substring",
			body: `{"case": "c", "operation": "grpc_Ping", "controllerReply": {}, "expectedErrorSubstring": "boom"}`,
			want: `a grpc case answers a reply or a status, never both`,
		},
		{
			name: "an http status",
			body: `{"case": "c", "operation": "grpc_Ping", "controllerReply": {}, "expectedStatus": 200}`,
			want: `expectedStatus is an HTTP status and a grpc case carries none`,
		},
		{
			name: "an expected body",
			body: `{"case": "c", "operation": "grpc_Ping", "controllerReply": {}, "expectedBody": {}}`,
			want: `a grpc case reads controllerReply back over the wire, drop expectedBody`,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			_, err := vectorsrust.Generate([]byte(helloSpec), []byte(`{"cases": [`+tc.body+`]}`), callOptions())
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("generating reported %v, want %q", err, tc.want)
			}
		})
	}
}

