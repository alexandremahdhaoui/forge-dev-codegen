func TestASeedIsRefusedWhenTheCellNamesNoRngPortOrTheCaseNeverPushes(t *testing.T) {
	tests := []struct {
		name string
		opts vectorsrust.Options
		body string
		want string
	}{
		{
			name: "no rng port",
			opts: callOptions(),
			body: `{"case": "c", "operation": "grpc_Ping", "controllerReply": {}, "seed": 7}`,
			want: `it carries a seed and the cell names no rng port under layout.rng`,
		},
		{
			name: "a seed below zero",
			opts: sessionOptions(),
			body: `{"case": "c", "operation": "udp_counter", "seed": -1, "expectPush": {"sessionIds": ["0123456789abcdef"]}}`,
			want: `seed -1 is below zero`,
		},
		{
			name: "a seed on a case that never pushes",
			opts: sessionOptions(),
			body: `{"case": "c", "operation": "udp_echo", "input": {"sessionId": "0123456789abcdef", "payload": "songe"}, "controllerReply": {"payload": "songe"}, "expectedBody": {"payload": "songe"}, "seed": 7}`,
			want: `seed belongs to a case whose controller pushes`,
		},
		{
			name: "a seed no payload field reads",
			opts: sessionOptions(),
			body: `{"case": "c", "operation": "udp_counter", "seed": 7, "expectPush": {"sessionIds": ["0123456789abcdef"], "payload": {"tick": 3}}}`,
			want: `no field of expectPush.payload reads <seed>`,
		},
		{
			name: "a payload reading the seed with no seed",
			opts: sessionOptions(),
			body: `{"case": "c", "operation": "udp_counter", "expectPush": {"sessionIds": ["0123456789abcdef"], "payload": {"tick": "<seed>"}}}`,
			want: `field "tick" reads <seed> and the case carries no seed`,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			_, err := vectorsrust.Generate([]byte(helloSpec), []byte(`{"cases": [`+tc.body+`]}`), tc.opts)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("generating reported %v, want %q", err, tc.want)
			}
		})
	}
}

