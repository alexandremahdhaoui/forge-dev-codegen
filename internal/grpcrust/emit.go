const header = "// Code generated by grpc-rust-tonic (forge-dev-codegen). DO NOT EDIT."

// Generate reads one proto3 document and answers the rust files of every
// service it declares: a client adapter and a port trait for calling out,
// a driver for serving, plain message types, and the build.rs plus proto
// copy tonic-build needs to compile it.
func Generate(doc []byte, opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the skeleton: the service name is required")
	}

	if opts.CoreDir == "" {
		opts.CoreDir = "core"
	}

	if opts.AppDir == "" {
		opts.AppDir = "app"
	}

	spec, err := Parse(doc)
	if err != nil {
		return nil, err
	}

	if len(spec.Services) == 0 {
		return nil, fmt.Errorf("emitting the skeleton: the proto document declares no service")
	}

	core := path.Join(opts.CoreDir, "src")
	app := path.Join(opts.AppDir, "src")

	files := []File{}

	for _, svc := range spec.Services {
		v, err := buildServiceView(spec, svc, opts)
		if err != nil {
			return nil, err
		}

		adapter, err := render("adapter", v)
		if err != nil {
			return nil, err
		}

		driver, err := render("driver", v)
		if err != nil {
			return nil, err
		}

		portFile, err := render("port", v)
		if err != nil {
			return nil, err
		}

		types, err := render("types", v)
		if err != nil {
			return nil, err
		}

		files = append(files,
			File{Path: path.Join(app, "adapter", "zz_generated_"+v.ServiceSnake+"_grpc_client.rs"), Content: adapter},
			File{Path: path.Join(app, "driver", "zz_generated_"+v.ServiceSnake+"_grpc_driver.rs"), Content: driver},
			File{Path: path.Join(core, "port", "zz_generated_"+v.ServiceSnake+"_client.rs"), Content: portFile},
			File{Path: path.Join(core, "types", "zz_generated_"+v.ServiceSnake+"_messages.rs"), Content: types},
		)
	}

	build, err := render("build", map[string]any{"Header": header, "Name": opts.Service})
	if err != nil {
		return nil, err
	}

	files = append(files,
		File{Path: path.Join(opts.AppDir, "zz_generated_build.rs"), Content: build},
		File{Path: path.Join(opts.AppDir, "proto", opts.Service+".proto"), Content: string(doc)},
	)

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })

	return files, nil
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

