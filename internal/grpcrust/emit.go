const header = "// Code generated by grpc-rust-tonic (forge-dev-codegen). DO NOT EDIT."

const DefaultCell = "grpc"

var cellIdent = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

func checkCell(name string) error {
	if cellIdent.MatchString(name) && !rustKeywords[name] {
		return nil
	}

	return fmt.Errorf("emitting the skeleton: cell %q is not a name Rust can spell as a module, use lowercase letters, digits and underscores and start with a letter", name)
}

func sideOfLayer(layer string) string {
	if layer == "adapter" || layer == "driver" {
		return "app"
	}

	return "core"
}

type modEntry struct {
	Module string
	Alias  string
}

type layerMod struct {
	Header  string
	Entries []modEntry
}

func Generate(doc []byte, opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the skeleton: the service name is required")
	}

	if opts.Cell == "" {
		opts.Cell = DefaultCell
	}

	if err := checkCell(opts.Cell); err != nil {
		return nil, err
	}

	if opts.Side != "" && opts.Side != "core" && opts.Side != "app" {
		return nil, fmt.Errorf("emitting the skeleton: side must be core, app or empty, got %q", opts.Side)
	}

	spec, err := Parse(doc)
	if err != nil {
		return nil, err
	}

	if len(spec.Services) == 0 {
		return nil, fmt.Errorf("emitting the skeleton: the proto document declares no service")
	}

	files := []File{}

	add := func(side, p, name string, data any, writeOnce bool) error {
		if opts.Side != "" && opts.Side != side {
			return nil
		}

		content, err := render(name, data)
		if err != nil {
			return err
		}

		files = append(files, File{Path: p, Content: content, WriteOnce: writeOnce})

		return nil
	}

	entries := map[string][]modEntry{}

	mount := func(layer string, entry modEntry) {
		entries[layer] = append(entries[layer], entry)
	}

	for _, svc := range spec.Services {
		v, err := buildServiceView(spec, svc, opts)
		if err != nil {
			return nil, err
		}

		steps := []func() error{
			func() error {
				return add("app", path.Join("adapter", "zz_generated_"+v.ServiceSnake+"_grpc_client.rs"), "adapter", v, false)
			},
			func() error {
				return add("app", path.Join("driver", "zz_generated_"+v.ServiceSnake+"_grpc_driver.rs"), "driver", v, false)
			},
			func() error {
				return add("core", path.Join("port", "zz_generated_"+v.ServiceSnake+"_client.rs"), "port", v, false)
			},
			func() error {
				return add("core", path.Join("types", "zz_generated_"+v.ServiceSnake+"_messages.rs"), "types", v, false)
			},
			func() error {
				return add("core", path.Join("controller", "zz_generated_"+v.ControllerSnake+"_controller.rs"), "controller", v, false)
			},
			func() error {
				return add("core", path.Join("hand", v.ControllerSnake+"_controller.rs"), "hand", v, true)
			},
		}

		for _, step := range steps {
			if err := step(); err != nil {
				return nil, err
			}
		}

		mount("adapter", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_grpc_client", Alias: v.ServiceSnake + "_grpc_client"})
		mount("driver", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_grpc_driver", Alias: v.ServiceSnake + "_grpc_driver"})
		mount("port", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_client", Alias: v.ServiceSnake + "_client"})
		mount("types", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_messages", Alias: v.ServiceSnake + "_messages"})
		mount("controller", modEntry{Module: "zz_generated_" + v.ControllerSnake + "_controller", Alias: v.ControllerSnake + "_controller"})
		mount("hand", modEntry{Module: v.ControllerSnake + "_controller"})
	}

	cellLayers := []string{}

	for _, layer := range []string{"adapter", "controller", "driver", "hand", "port", "types"} {
		if opts.Side != "" && opts.Side != sideOfLayer(layer) {
			continue
		}

		cellLayers = append(cellLayers, layer)

		mod := layerMod{Header: header, Entries: entries[layer]}
		sort.Slice(mod.Entries, func(i, j int) bool { return mod.Entries[i].Module < mod.Entries[j].Module })

		if err := add(sideOfLayer(layer), path.Join(layer, "mod.rs"), "layer_mod", mod, false); err != nil {
			return nil, err
		}
	}

	cell, err := render("cell_mod", map[string]any{"Header": header, "Layers": cellLayers})
	if err != nil {
		return nil, err
	}

	files = append(files, File{Path: "mod.rs", Content: cell})

	protoName := Snake(spec.Services[0].Name)
	buildData := map[string]any{"Header": header, "Cell": opts.Cell, "Name": protoName}

	if err := add("app", "zz_generated_build.rs", "build", buildData, false); err != nil {
		return nil, err
	}

	if opts.Side == "" || opts.Side == "app" {
		files = append(files, File{
			Path:    path.Join("proto", "zz_generated_"+protoName+".proto"),
			Content: header + "\n" + string(doc),
		})
	}

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })

	return files, nil
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

