func TestASideAnswersOneCrateAtItsOwnRoot(t *testing.T) {
	tests := []struct {
		side string
		opts grpcrust.Options
		want []string
	}{
		{
			side: "core",
			opts: grpcrust.Options{Service: "songe-hello", Side: "core", CoreDir: "."},
			want: []string{
				"src/controller/zz_generated_hello_controller.rs",
				"src/hand/hello_controller.rs",
				"src/port/zz_generated_hello_client.rs",
				"src/types/zz_generated_hello_messages.rs",
			},
		},
		{
			side: "app",
			opts: grpcrust.Options{Service: "songe-hello", Side: "app", AppDir: "."},
			want: []string{
				"proto/zz_generated_songe-hello.proto",
				"src/adapter/zz_generated_hello_grpc_client.rs",
				"src/driver/zz_generated_hello_grpc_driver.rs",
				"zz_generated_build.rs",
			},
		},
	}

	for _, tt := range tests {
		t.Run("the "+tt.side+" side answers only its own files", func(t *testing.T) {
			files, err := grpcrust.Generate([]byte(helloProto), tt.opts)
			if err != nil {
				t.Fatalf("generating: %v", err)
			}

			got := []string{}
			for _, f := range files {
				got = append(got, f.Path)
			}

			if !reflect.DeepEqual(got, tt.want) {
				t.Fatalf("emitted paths\n got %q\nwant %q", got, tt.want)
			}
		})
	}
}

