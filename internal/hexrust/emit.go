var Layers = []string{"adapter", "controller", "driver", "port", "types"}

var allowingLayers = map[string]bool{"adapter": true, "driver": true}

var reservedCellNames = map[string]bool{
	"adapter": true, "bin": true, "config": true, "controller": true,
	"driver": true, "port": true, "types": true,
}

type Options struct {
	Service string
	SrcDir  string
	Cells   []string
	Wiring  []byte
}

type File struct {
	Path    string
	Content string
}

func checkCells(cells []string) error {
	seen := map[string]bool{}

	for _, cell := range cells {
		if !rustname.IsModuleName(cell) {
			return fmt.Errorf("mounting cell %q: it is not a name Rust can spell as a module, use lowercase letters, digits and underscores and start with a letter", cell)
		}

		if reservedCellNames[cell] {
			return fmt.Errorf("mounting cell %q: the crate root already owns that module, name the cell something else", cell)
		}

		if seen[cell] {
			return fmt.Errorf("mounting cell %q: it is listed twice", cell)
		}

		seen[cell] = true
	}

	return nil
}

func CellsFromLayout(layout map[string]interface{}) ([]string, error) {
	raw, ok := layout["cells"]
	if !ok {
		return nil, nil
	}

	entries, ok := raw.([]interface{})
	if !ok {
		return nil, fmt.Errorf("reading cells: it is a list of module directory names under src")
	}

	names := make([]string, 0, len(entries))

	for i, entry := range entries {
		name, ok := entry.(string)
		if !ok || name == "" {
			return nil, fmt.Errorf("reading cells entry %d: it is a name, not %v", i, entry)
		}

		names = append(names, name)
	}

	return names, nil
}

func ReadManifests(srcDir string, cells []string) ([]cellmanifest.Manifest, error) {
	manifests := make([]cellmanifest.Manifest, 0, len(cells))

	for _, cell := range cells {
		dir := filepath.Join(srcDir, "src", cell)

		if _, err := os.Stat(filepath.Join(dir, CellConfigFile)); err != nil {
			return nil, fmt.Errorf(
				"mounting cell %q: src/%s/%s is missing, a listed cell owns its own generator",
				cell, cell, CellConfigFile,
			)
		}

		manifestPath := filepath.Join(dir, cellmanifest.FileName)

		if _, err := os.Stat(manifestPath); err != nil {
			return nil, fmt.Errorf(
				"mounting cell %q: src/%s/%s is missing, build the cell before the skeleton",
				cell, cell, cellmanifest.FileName,
			)
		}

		m, err := cellmanifest.Read(manifestPath)
		if err != nil {
			return nil, fmt.Errorf("mounting cell %q: %w", cell, err)
		}

		manifests = append(manifests, m)
	}

	return manifests, nil
}

func Generate(opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the skeleton: the service name is required")
	}

	if err := checkCells(opts.Cells); err != nil {
		return nil, fmt.Errorf("emitting the skeleton: %w", err)
	}

	if len(opts.Wiring) == 0 {
		return nil, fmt.Errorf("emitting the skeleton: the cell names no wiring file, add wiring.specPath beside openapi")
	}

	wiring, err := ParseWiring(opts.Wiring)
	if err != nil {
		return nil, err
	}

	manifests, err := ReadManifests(opts.SrcDir, opts.Cells)
	if err != nil {
		return nil, err
	}

	merged, err := cellmanifest.Merge(manifests)
	if err != nil {
		return nil, err
	}

	p, err := buildPlan(merged, wiring, opts)
	if err != nil {
		return nil, err
	}

	files := []File{}

	add := func(target, name string, data any) error {
		content, err := render(name, data)
		if err != nil {
			return err
		}

		files = append(files, File{Path: target, Content: content})

		return nil
	}

	steps := []func() error{
		func() error { return add(path.Join("src", "lib.rs"), "lib", p) },
		func() error { return add(path.Join("src", "config", "mod.rs"), "config_mod", p) },
		func() error {
			return add(path.Join("src", "bin", "zz_generated_"+p.BinaryIdent+".rs"), "main", p)
		},
	}

	for _, layer := range Layers {
		layer := layer

		mod := map[string]any{
			"Header":  header,
			"Allow":   allowingLayers[layer],
			"Configs": []handConfigPlan{},
		}

		if layer == "adapter" {
			configs := append([]handConfigPlan{}, p.HandConfigs...)
			sort.Slice(configs, func(i, j int) bool { return configs[i].Module < configs[j].Module })

			mod["Configs"] = configs
		}

		steps = append(steps, func() error {
			return add(path.Join("src", layer, "mod.rs"), "layer_mod", mod)
		})
	}

	for _, hand := range p.HandConfigs {
		hand := hand

		steps = append(steps, func() error {
			return add(
				path.Join("src", "adapter", "zz_generated_"+hand.Module+"_config.rs"),
				"hand_config",
				map[string]any{"Header": header, "Config": hand},
			)
		})
	}

	for _, step := range steps {
		if err := step(); err != nil {
			return nil, err
		}
	}

	spec, err := ConfigSpec(p)
	if err != nil {
		return nil, err
	}

	files = append(files, File{Path: ConfigSpecFile, Content: spec})

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })

	return files, nil
}

type specProperty struct {
	Type        string `json:"type"`
	Default     *any   `json:"default,omitempty"`
	Description string `json:"description,omitempty"`
	Env         string `json:"x-env,omitempty"`
	Flag        string `json:"x-flag,omitempty"`
}

type specSchema struct {
	Type       string                  `json:"type"`
	Properties map[string]specProperty `json:"properties"`
}

type specComponents struct {
	Schemas map[string]specSchema `json:"schemas"`
}

type specInfo struct {
	Title   string `json:"title"`
	Version string `json:"version"`
}

type specDocument struct {
	OpenAPI    string         `json:"openapi"`
	Info       specInfo       `json:"info"`
	Components specComponents `json:"components"`
}

func describe(key specKey, binary string) string {
	if key.Description != "" {
		return key.Description
	}

	return "The " + strings.ReplaceAll(key.Key, "_", " ") + " of " + binary
}

func EnvName(binary, key string) string {
	return strings.ToUpper(rustname.Snake(binary)) + "_" + strings.ToUpper(rustname.Snake(key))
}

func FlagName(key string) string {
	return strings.ReplaceAll(rustname.Snake(key), "_", "-")
}

func ConfigSpec(p plan) (string, error) {
	properties := map[string]specProperty{}

	for _, key := range p.Keys {
		property := specProperty{
			Type:        key.Type,
			Description: describe(key, p.Binary),
			Env:         EnvName(p.Binary, key.Key),
			Flag:        FlagName(key.Key),
		}

		if key.Default != nil {
			value := key.Default
			property.Default = &value
		}

		properties[key.Key] = property
	}

	doc := specDocument{
		OpenAPI: "3.0.3",
		Info:    specInfo{Title: p.Binary + " config", Version: "0.1.0"},
		Components: specComponents{
			Schemas: map[string]specSchema{
				"Spec": {Type: "object", Properties: properties},
			},
		},
	}

	body, err := yaml.Marshal(doc)
	if err != nil {
		return "", fmt.Errorf("emitting the config spec: %w", err)
	}

	return yamlHeader + "\n" + string(body), nil
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

