const header = "// Code generated by udp-rust (forge-dev-codegen). DO NOT EDIT."

const Generator = "udp-rust (forge-dev-codegen)"

const DefaultCell = "udp"

const DefaultAddress = "127.0.0.1:0"

const DefaultEndpoint = "127.0.0.1:0"

const DefaultTimeoutMs = 2000

const DefaultSessions = 64

const DefaultTickMs = 1000

var Layers = []string{"adapter", "controller", "driver", "port", "types"}

var allowingLayers = map[string]bool{"adapter": true, "driver": true}

func checkCell(name string) error {
	if rustname.IsModuleName(name) {
		return nil
	}

	return fmt.Errorf("emitting the skeleton: cell %q is not a name Rust can spell as a module, use lowercase letters, digits and underscores and start with a letter", name)
}

type modEntry struct {
	Module  string
	Alias   string
	Exports []string
}

type layerMod struct {
	Header   string
	Allow    bool
	Entries  []modEntry
	UserMods []string
}

func Generate(doc []byte, opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the skeleton: the service name is required")
	}

	if opts.Cell == "" {
		opts.Cell = DefaultCell
	}

	if err := checkCell(opts.Cell); err != nil {
		return nil, err
	}

	spec, err := grpcrust.Parse(doc)
	if err != nil {
		return nil, err
	}

	if len(spec.Services) == 0 {
		return nil, fmt.Errorf("emitting the skeleton: the proto document declares no service")
	}

	if err := checkSessionNames(spec, opts); err != nil {
		return nil, err
	}

	files := []File{}

	add := func(p, name string, data any) error {
		content, err := render(name, data)
		if err != nil {
			return err
		}

		files = append(files, File{Path: p, Content: content})

		return nil
	}

	entries := map[string][]modEntry{}
	userMods := map[string][]string{}

	mount := func(layer string, entry modEntry) {
		entries[layer] = append(entries[layer], entry)
	}

	manifest := cellmanifest.Manifest{
		Version:   cellmanifest.Version,
		Cell:      opts.Cell,
		Generator: Generator,
	}

	methodByHash := map[uint8]string{}
	only := len(spec.Services) == 1
	session := false

	for _, svc := range spec.Services {
		v, err := buildServiceView(spec, svc, opts, only)
		if err != nil {
			return nil, err
		}

		for _, rpc := range v.Rpcs {
			other, taken := methodByHash[rpc.Hash]
			if taken {
				return nil, fmt.Errorf("hashing the methods of package %q: %s and %s both fold to the function hash %d, rename one of them", spec.Package, other, rpc.FullMethod, rpc.Hash)
			}

			methodByHash[rpc.Hash] = rpc.FullMethod
		}

		steps := []func() error{
			func() error {
				return add(path.Join("adapter", "zz_generated_"+v.ClientModule+".rs"), "adapter", v)
			},
			func() error {
				return add(path.Join("driver", "zz_generated_"+v.DriverModule+".rs"), "driver", v)
			},
			func() error {
				return add(path.Join("port", "zz_generated_"+v.ServiceSnake+"_client.rs"), "port", v)
			},
			func() error {
				return add(path.Join("types", "zz_generated_"+v.ServiceSnake+"_messages.rs"), "types", v)
			},
			func() error {
				return add(path.Join("controller", "zz_generated_"+v.ControllerSnake+"_controller.rs"), "controller", v)
			},
			func() error {
				return add(path.Join("controller", "zz_generated_"+v.ServiceSnake+"_codec.rs"), "codec", v)
			},
		}

		if v.Session {
			session = true

			steps = append(steps,
				func() error {
					return add(path.Join("adapter", "zz_generated_"+v.BroadcastAdapter+".rs"), "broadcast_adapter", v)
				},
				func() error {
					return add(path.Join("adapter", "zz_generated_"+v.PeerTableAdapter+".rs"), "peer_table_adapter", v)
				},
				func() error {
					return add(path.Join("driver", "zz_generated_"+v.TickModule+".rs"), "tick", v)
				},
				func() error {
					return add(path.Join("port", "zz_generated_"+v.GateModule+".rs"), "gate", v)
				},
				func() error {
					return add(path.Join("port", "zz_generated_"+v.BroadcastModule+".rs"), "broadcast", v)
				},
				func() error {
					return add(path.Join("port", "zz_generated_"+v.PeerTableModule+".rs"), "peer_table", v)
				},
				func() error {
					return add(path.Join("types", "zz_generated_"+v.PushModule+".rs"), "push", v)
				},
			)
		}

		for _, step := range steps {
			if err := step(); err != nil {
				return nil, err
			}
		}

		mount("adapter", modEntry{Module: "zz_generated_" + v.ClientModule, Alias: v.ClientModule})
		mount("driver", modEntry{Module: "zz_generated_" + v.DriverModule, Alias: v.DriverModule})
		mount("port", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_client", Alias: v.ServiceSnake + "_client"})
		mount("types", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_messages", Alias: v.ServiceSnake + "_messages"})
		mount("controller", modEntry{
			Module:  "zz_generated_" + v.ControllerSnake + "_controller",
			Exports: []string{v.ControllerTrait, v.ControllerError, v.ControllerTrait + "Impl"},
		})
		mount("controller", modEntry{Module: "zz_generated_" + v.ServiceSnake + "_codec", Alias: v.ServiceSnake + "_codec"})
		userMods["controller"] = append(userMods["controller"], v.ControllerSnake+"_controller")

		if v.Session {
			mount("adapter", modEntry{Module: "zz_generated_" + v.BroadcastAdapter, Alias: v.BroadcastAdapter})
			mount("adapter", modEntry{Module: "zz_generated_" + v.PeerTableAdapter, Alias: v.PeerTableAdapter})
			mount("driver", modEntry{Module: "zz_generated_" + v.TickModule, Alias: v.TickModule})
			mount("port", modEntry{Module: "zz_generated_" + v.GateModule, Alias: v.GateModule})
			mount("port", modEntry{Module: "zz_generated_" + v.BroadcastModule, Alias: v.BroadcastModule})
			mount("port", modEntry{Module: "zz_generated_" + v.PeerTableModule, Alias: v.PeerTableModule})
			mount("types", modEntry{Module: "zz_generated_" + v.PushModule, Alias: v.PushModule})
		}

		addServiceToManifest(&manifest, v)
	}

	if err := add(path.Join("types", "zz_generated_context.rs"), "context", map[string]any{"Header": header}); err != nil {
		return nil, err
	}

	mount("types", modEntry{Module: "zz_generated_context", Alias: "context"})

	if session {
		if err := add(path.Join("types", "zz_generated_admission.rs"), "admission", map[string]any{"Header": header}); err != nil {
			return nil, err
		}

		mount("types", modEntry{Module: "zz_generated_admission", Alias: "admission"})
	}

	for _, layer := range Layers {
		mod := layerMod{
			Header:   header,
			Allow:    allowingLayers[layer],
			Entries:  entries[layer],
			UserMods: userMods[layer],
		}
		sort.Slice(mod.Entries, func(i, j int) bool { return mod.Entries[i].Module < mod.Entries[j].Module })
		sort.Strings(mod.UserMods)

		if err := add(path.Join(layer, "mod.rs"), "layer_mod", mod); err != nil {
			return nil, err
		}
	}

	cell, err := render("cell_mod", map[string]any{"Header": header, "Layers": Layers})
	if err != nil {
		return nil, err
	}

	files = append(files, File{Path: "mod.rs", Content: cell})

	body, err := cellmanifest.Marshal(manifest)
	if err != nil {
		return nil, fmt.Errorf("emitting the skeleton: %w", err)
	}

	files = append(files, File{Path: cellmanifest.FileName, Content: string(body)})

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })

	return files, nil
}

func addServiceToManifest(m *cellmanifest.Manifest, v serviceView) {
	controllerPorts := []string{}
	driverPorts := []string{}

	if v.Session {
		controllerPorts = []string{v.BroadcastTrait}
		driverPorts = []string{v.GateTrait, v.PeerTableTrait}
	}

	m.Provides.Controllers = append(m.Provides.Controllers, cellmanifest.Controller{
		Trait:  v.ControllerTrait,
		Impl:   v.ControllerTrait + "Impl",
		Module: v.ModulePrefix + "controller",
		Ports:  controllerPorts,
	})

	m.Provides.Drivers = append(m.Provides.Drivers, cellmanifest.Driver{
		Name:     v.DriverName,
		Type:     v.DriverStruct,
		Module:   v.ModulePrefix + "driver::" + v.DriverModule,
		Requires: []string{v.ControllerTrait},
		Ports:    driverPorts,
		Config: map[string]cellmanifest.ConfigField{
			"addr": {
				Type:        cellmanifest.FieldTypeString,
				Default:     DefaultAddress,
				Description: "The host and port the " + v.ServiceSnake + " udp driver binds",
			},
		},
	})

	m.Provides.Ports = append(m.Provides.Ports, cellmanifest.Port{
		Trait:  v.ClientTrait,
		Module: v.ModulePrefix + "port::" + v.ServiceSnake + "_client",
	})

	m.Provides.Adapters = append(m.Provides.Adapters, cellmanifest.Adapter{
		Name:       v.ClientName,
		Type:       v.ClientStruct,
		Module:     v.ModulePrefix + "adapter::" + v.ClientModule,
		Implements: v.ClientTrait,
		Config: map[string]cellmanifest.ConfigField{
			"address": {
				Type:        cellmanifest.FieldTypeString,
				Default:     DefaultEndpoint,
				Description: "The host and port the " + v.ServiceSnake + " client sends datagrams to",
			},
			"session_id": {
				Type:        cellmanifest.FieldTypeString,
				Default:     "",
				Description: "The session the " + v.ServiceSnake + " client opens, sixteen bytes, padded with zeros",
			},
			"timeout_ms": {
				Type:        cellmanifest.FieldTypeDuration,
				Default:     DefaultTimeoutMs,
				Description: "How long the " + v.ServiceSnake + " client waits for one answer",
			},
		},
	})

	if !v.Session {
		return
	}

	m.Provides.Drivers = append(m.Provides.Drivers, cellmanifest.Driver{
		Name:     v.TickName,
		Type:     v.TickStruct,
		Module:   v.ModulePrefix + "driver::" + v.TickModule,
		Requires: []string{v.ControllerTrait},
		Ports:    []string{v.PeerTableTrait},
		Config: map[string]cellmanifest.ConfigField{
			"interval_ms": {
				Type:        cellmanifest.FieldTypeInteger,
				Default:     DefaultTickMs,
				Description: "How many milliseconds the " + v.ServiceSnake + " tick driver waits between two ticks",
			},
		},
	})

	m.Provides.Ports = append(m.Provides.Ports,
		cellmanifest.Port{Trait: v.GateTrait, Module: v.ModulePrefix + "port::" + v.GateModule},
		cellmanifest.Port{Trait: v.BroadcastTrait, Module: v.ModulePrefix + "port::" + v.BroadcastModule},
		cellmanifest.Port{Trait: v.PeerTableTrait, Module: v.ModulePrefix + "port::" + v.PeerTableModule},
	)

	m.Provides.Adapters = append(m.Provides.Adapters,
		cellmanifest.Adapter{
			Name:       v.PeerTableName,
			Type:       v.PeerTableStruct,
			Module:     v.ModulePrefix + "adapter::" + v.PeerTableAdapter,
			Implements: v.PeerTableTrait,
			Fallible:   true,
			Config: map[string]cellmanifest.ConfigField{
				"max_sessions": {
					Type:        cellmanifest.FieldTypeInteger,
					Default:     DefaultSessions,
					Description: "How many sessions the " + v.ServiceSnake + " peer table holds before it refuses a new one",
				},
			},
		},
		cellmanifest.Adapter{
			Name:       v.BroadcastName,
			Type:       v.BroadcastStruct,
			Module:     v.ModulePrefix + "adapter::" + v.BroadcastAdapter,
			Implements: v.BroadcastTrait,
			Ports:      []string{v.PeerTableTrait},
		},
	)
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

