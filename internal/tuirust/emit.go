const Generator = "tui-rust (forge-dev-codegen)"

const DefaultCell = "tui"

var Layers = []string{"adapter", "controller", "driver", "port", "types"}

var allowingLayers = map[string]bool{"adapter": true, "driver": true}

func checkCell(name string) error {
	if rustname.IsModuleName(name) {
		return nil
	}

	return fmt.Errorf("emitting the cell: cell %q is not a name Rust can spell as a module, use lowercase letters, digits and underscores and start with a letter", name)
}

type modEntry struct {
	Module  string
	Alias   string
	Exports []string
}

type layerMod struct {
	Header   string
	Allow    bool
	Entries  []modEntry
	UserMods []string
}

func Generate(doc []byte, opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the cell: the service name is required")
	}

	if opts.Cell == "" {
		opts.Cell = DefaultCell
	}

	if err := checkCell(opts.Cell); err != nil {
		return nil, err
	}

	spec, err := ParseSpec(doc)
	if err != nil {
		return nil, fmt.Errorf("emitting the cell: %w", err)
	}

	v, err := buildCellView(spec, opts)
	if err != nil {
		return nil, fmt.Errorf("emitting the cell: %w", err)
	}

	files := []File{}

	add := func(p, name string) error {
		content, err := render(name, v)
		if err != nil {
			return err
		}

		files = append(files, File{Path: p, Content: content})

		return nil
	}

	steps := []struct {
		path string
		tmpl string
	}{
		{path.Join("adapter", "zz_generated_"+v.ScreenModule+".rs"), "screen_adapter"},
		{path.Join("adapter", "zz_generated_"+v.KeyboardModule+".rs"), "keyboard_adapter"},
		{path.Join("controller", "zz_generated_"+v.ControllerModule+".rs"), "controller"},
		{path.Join("driver", "zz_generated_"+v.DriverModule+".rs"), "driver"},
		{path.Join("port", "zz_generated_screen.rs"), "screen_port"},
		{path.Join("port", "zz_generated_keyboard.rs"), "keyboard_port"},
		{path.Join("types", "zz_generated_frame.rs"), "frame"},
		{path.Join("types", "zz_generated_key.rs"), "key"},
	}

	for _, step := range steps {
		if err := add(step.path, step.tmpl); err != nil {
			return nil, err
		}
	}

	entries := map[string][]modEntry{
		"adapter": {
			{Module: "zz_generated_" + v.ScreenModule, Alias: v.ScreenModule},
			{Module: "zz_generated_" + v.KeyboardModule, Alias: v.KeyboardModule},
		},
		"controller": {
			{
				Module:  "zz_generated_" + v.ControllerModule,
				Exports: []string{v.ControllerTrait, v.ControllerError, v.ControllerImpl},
			},
		},
		"driver": {
			{Module: "zz_generated_" + v.DriverModule, Alias: v.DriverModule},
		},
		"port": {
			{Module: "zz_generated_screen", Alias: "screen"},
			{Module: "zz_generated_keyboard", Alias: "keyboard"},
		},
		"types": {
			{Module: "zz_generated_frame", Alias: "frame"},
			{Module: "zz_generated_key", Alias: "key"},
		},
	}

	userMods := map[string][]string{"controller": {v.ControllerModule}}

	for _, layer := range Layers {
		mod := layerMod{
			Header:   header,
			Allow:    allowingLayers[layer],
			Entries:  entries[layer],
			UserMods: userMods[layer],
		}
		sort.Slice(mod.Entries, func(i, j int) bool { return mod.Entries[i].Module < mod.Entries[j].Module })

		content, err := render("layer_mod", mod)
		if err != nil {
			return nil, err
		}

		files = append(files, File{Path: path.Join(layer, "mod.rs"), Content: content})
	}

	cell, err := render("cell_mod", map[string]any{"Header": header, "Layers": Layers})
	if err != nil {
		return nil, err
	}

	files = append(files, File{Path: "mod.rs", Content: cell})

	body, err := cellmanifest.Marshal(manifestOf(v))
	if err != nil {
		return nil, fmt.Errorf("emitting the cell: %w", err)
	}

	files = append(files, File{Path: cellmanifest.FileName, Content: string(body)})

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })

	return files, nil
}

func manifestOf(v cellView) cellmanifest.Manifest {
	m := cellmanifest.Manifest{
		Version:   cellmanifest.Version,
		Cell:      v.Cell,
		Generator: Generator,
	}

	m.Provides.Controllers = []cellmanifest.Controller{{
		Trait:  v.ControllerTrait,
		Impl:   v.ControllerImpl,
		Module: v.ModulePrefix + "controller",
	}}

	m.Provides.Drivers = []cellmanifest.Driver{{
		Name:     v.DriverName,
		Type:     v.DriverStruct,
		Module:   v.ModulePrefix + "driver::" + v.DriverModule,
		Requires: []string{v.ControllerTrait},
		Ports:    []string{"Screen", "Keyboard"},
		Config: map[string]cellmanifest.ConfigField{
			"tick_ms": {
				Type:        cellmanifest.FieldTypeDuration,
				Default:     v.TickMs,
				Description: "How long the " + v.Cell + " driver waits for a key before it ticks the controller",
			},
		},
	}}

	m.Provides.Ports = []cellmanifest.Port{
		{Trait: "Screen", Module: v.ModulePrefix + "port::screen"},
		{Trait: "Keyboard", Module: v.ModulePrefix + "port::keyboard"},
	}

	m.Provides.Adapters = []cellmanifest.Adapter{
		{
			Name:       v.ScreenName,
			Type:       v.ScreenAdapter,
			Module:     v.ModulePrefix + "adapter::" + v.ScreenModule,
			Implements: "Screen",
		},
		{
			Name:       v.KeyboardName,
			Type:       v.KeyboardAdapter,
			Module:     v.ModulePrefix + "adapter::" + v.KeyboardModule,
			Implements: "Keyboard",
		},
	}

	return m
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

