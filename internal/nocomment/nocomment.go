package nocomment

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type Finding struct {
	File string
	Line int
	Text string
}

type Options struct {
	RootDir   string
	Languages []string
	Exclude   []string
}

var defaultLanguages = []string{"go", "rust", "python", "typescript"}

var defaultExclude = []string{
	"zz_generated*",
	"**/zz_generated*",
	"**/docs/**",
}

var extensionsByLanguage = map[string][]string{
	"go":         {".go"},
	"rust":       {".rs"},
	"python":     {".py"},
	"typescript": {".ts", ".tsx"},
}

func Scan(opts Options) ([]Finding, error) {
	rootDir := opts.RootDir
	if rootDir == "" {
		rootDir = "."
	}

	languages := opts.Languages
	if len(languages) == 0 {
		languages = defaultLanguages
	}

	exclude := opts.Exclude
	if len(exclude) == 0 {
		exclude = defaultExclude
	}

	langByExt := map[string]string{}
	for _, lang := range languages {
		for _, ext := range extensionsByLanguage[lang] {
			langByExt[ext] = lang
		}
	}

	var findings []Finding

	err := filepath.Walk(rootDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			name := info.Name()
			if name == ".git" || name == "vendor" || name == "node_modules" || name == "target" {
				return filepath.SkipDir
			}
			return nil
		}

		relPath, err := filepath.Rel(rootDir, path)
		if err != nil {
			return fmt.Errorf("computing relative path for %q: %w", path, err)
		}
		relPath = filepath.ToSlash(relPath)

		if matchAny(exclude, relPath) {
			return nil
		}

		lang, ok := langByExt[filepath.Ext(path)]
		if !ok {
			return nil
		}

		content, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("reading %q: %w", path, err)
		}

		fileFindings := scanFile(lang, string(content))
		for _, f := range fileFindings {
			f.File = relPath
			findings = append(findings, f)
		}

		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("walking %q: %w", rootDir, err)
	}

	sort.Slice(findings, func(i, j int) bool {
		if findings[i].File != findings[j].File {
			return findings[i].File < findings[j].File
		}
		return findings[i].Line < findings[j].Line
	})

	return findings, nil
}

type rawComment struct {
	startLine int
	endLine   int
	text      string
}

func scanFile(lang string, content string) []Finding {
	lines := strings.Split(content, "\n")
	if len(lines) > 0 && strings.Contains(lines[0], "Code generated by") {
		return nil
	}

	comments := extractComments(lang, content)

	comments = dropShebang(comments)
	comments = dropLicenseHeader(comments, lines)

	findings := make([]Finding, 0, len(comments))
	for _, c := range comments {
		findings = append(findings, Finding{Line: c.startLine, Text: c.text})
	}
	return findings
}

func dropShebang(comments []rawComment) []rawComment {
	out := comments[:0:0]
	for _, c := range comments {
		if c.startLine == 1 && strings.HasPrefix(c.text, "#!") {
			continue
		}
		out = append(out, c)
	}
	return out
}

func dropLicenseHeader(comments []rawComment, lines []string) []rawComment {
	blankLine := len(lines) + 1
	for i, line := range lines {
		if strings.TrimSpace(line) == "" {
			blankLine = i + 1
			break
		}
	}
	headerLines := blankLine - 1
	if headerLines < 1 {
		return comments
	}

	covered := make([]bool, headerLines+1)
	for _, c := range comments {
		for l := c.startLine; l <= c.endLine && l <= headerLines; l++ {
			if l >= 1 {
				covered[l] = true
			}
		}
	}
	for l := 1; l <= headerLines; l++ {
		if !covered[l] {
			return comments
		}
	}

	out := comments[:0:0]
	for _, c := range comments {
		if c.startLine <= headerLines {
			continue
		}
		out = append(out, c)
	}
	return out
}

func extractComments(lang string, content string) []rawComment {
	runes := []rune(content)
	n := len(runes)

	var comments []rawComment
	line := 1
	i := 0

	inString := false
	triple := false
	quote := rune(0)

	for i < n {
		c := runes[i]

		if c == '\n' {
			line++
			i++
			continue
		}

		if inString {
			if c == '\\' && i+1 < n {
				i += 2
				continue
			}
			if triple {
				if i+2 < n && runes[i] == quote && runes[i+1] == quote && runes[i+2] == quote {
					i += 3
					inString = false
					continue
				}
				i++
				continue
			}
			if c == quote {
				inString = false
				i++
				continue
			}
			i++
			continue
		}

		if lang == "python" && c == '#' {
			start := i
			startLine := line
			for i < n && runes[i] != '\n' {
				i++
			}
			comments = append(comments, rawComment{
				startLine: startLine,
				endLine:   startLine,
				text:      strings.TrimSpace(string(runes[start:i])),
			})
			continue
		}

		if lang != "python" {
			if c == '/' && i+1 < n && runes[i+1] == '/' {
				start := i
				startLine := line
				for i < n && runes[i] != '\n' {
					i++
				}
				comments = append(comments, rawComment{
					startLine: startLine,
					endLine:   startLine,
					text:      strings.TrimSpace(string(runes[start:i])),
				})
				continue
			}
			if c == '/' && i+1 < n && runes[i+1] == '*' {
				start := i
				startLine := line
				i += 2
				for i+1 < n && (runes[i] != '*' || runes[i+1] != '/') {
					if runes[i] == '\n' {
						line++
					}
					i++
				}
				end := i + 2
				if end > n {
					end = n
				}
				comments = append(comments, rawComment{
					startLine: startLine,
					endLine:   line,
					text:      strings.TrimSpace(string(runes[start:end])),
				})
				i = end
				continue
			}
		}

		if lang == "python" && (c == '\'' || c == '"') {
			if i+2 < n && runes[i+1] == c && runes[i+2] == c {
				inString = true
				triple = true
				quote = c
				i += 3
				continue
			}
			inString = true
			triple = false
			quote = c
			i++
			continue
		}

		if lang != "python" && (c == '"' || c == '\'' || ((lang == "typescript" || lang == "go") && c == '`')) {
			inString = true
			triple = false
			quote = c
			i++
			continue
		}

		i++
	}

	return comments
}

func matchAny(patterns []string, relPath string) bool {
	for _, p := range patterns {
		if matchGlob(p, relPath) {
			return true
		}
	}
	return false
}

func matchGlob(pattern, path string) bool {
	patSegs := strings.Split(pattern, "/")
	pathSegs := strings.Split(path, "/")
	return globMatch(patSegs, pathSegs)
}

func globMatch(patSegs, pathSegs []string) bool {
	if len(patSegs) == 0 {
		return len(pathSegs) == 0
	}

	head := patSegs[0]
	if head == "**" {
		if globMatch(patSegs[1:], pathSegs) {
			return true
		}
		if len(pathSegs) > 0 && globMatch(patSegs, pathSegs[1:]) {
			return true
		}
		return false
	}

	if len(pathSegs) == 0 {
		return false
	}

	matched, err := filepath.Match(head, pathSegs[0])
	if err != nil || !matched {
		return false
	}

	return globMatch(patSegs[1:], pathSegs[1:])
}
