type Options struct {
	Service   string
	Cell      string
	Root      bool
	Header    string
	Generator string
}

type File struct {
	Path    string
	Content string
}

type modEntry struct {
	Module  string
	Alias   string
	Exports []string
}

type layerMod struct {
	Header   string
	Allow    bool
	Entries  []modEntry
	UserMods []string
}

func Generate(doc []byte, opts Options) ([]File, error) {
	if opts.Service == "" {
		return nil, fmt.Errorf("emitting the rest cell: the service name is required")
	}

	if err := checkName("service", opts.Service); err != nil {
		return nil, fmt.Errorf("emitting the rest cell: %w", err)
	}

	if opts.Cell == "" {
		opts.Cell = DefaultCell
	}

	if !IsModuleName(opts.Cell) {
		return nil, fmt.Errorf("emitting the rest cell: cell %q is not a name Rust can spell as a module, use lowercase letters, digits and underscores and start with a letter", opts.Cell)
	}

	spec, err := Parse(doc)
	if err != nil {
		return nil, err
	}

	v := buildView(spec, opts)

	if opts.Header != "" {
		v.Header = opts.Header
	}

	root := ""
	if opts.Root {
		root = "src"
	}

	files := []File{}

	add := func(p, name string, data any) error {
		content, err := render(name, data)
		if err != nil {
			return err
		}

		files = append(files, File{Path: p, Content: content})

		return nil
	}

	entries := map[string][]modEntry{
		"driver": {
			{Module: "zz_generated_wire", Alias: "wire"},
			{Module: "zz_generated_http_driver", Alias: "http_driver"},
		},
	}
	userMods := map[string][]string{}

	mount := func(layer string, entry modEntry) {
		entries[layer] = append(entries[layer], entry)
	}

	for _, t := range v.Types {
		mount("types", modEntry{Module: "zz_generated_" + t.Snake, Alias: t.Snake})
	}

	for _, s := range v.Stores {
		mount("port", modEntry{Module: "zz_generated_" + s.PortSnake, Alias: s.PortSnake})
		mount("adapter", modEntry{Module: "zz_generated_" + s.Module, Alias: s.Module})
	}

	for _, c := range v.Controllers {
		mount("controller", modEntry{
			Module: "zz_generated_" + c.Snake + "_controller",
			Exports: []string{
				c.Pascal + "Controller",
				c.Pascal + "ControllerError",
				c.Pascal + "ControllerImpl",
			},
		})
		userMods["controller"] = append(userMods["controller"], c.Snake+"_controller")
	}

	steps := []func() error{
		func() error { return add(path.Join(root, "driver", "zz_generated_wire.rs"), "wire", v) },
		func() error {
			return add(path.Join(root, "driver", "zz_generated_http_driver.rs"), "http_driver", v)
		},
	}

	for _, t := range v.Types {
		t := t

		steps = append(steps, func() error {
			return add(path.Join(root, "types", "zz_generated_"+t.Snake+".rs"), "type", map[string]any{"Header": v.Header, "Type": t})
		})
	}

	for _, s := range v.Stores {
		s := s

		steps = append(steps,
			func() error {
				return add(path.Join(root, "port", "zz_generated_"+s.PortSnake+".rs"), "port", map[string]any{"Header": v.Header, "Store": s, "CratePath": v.CratePath})
			},
			func() error {
				return add(path.Join(root, "adapter", "zz_generated_"+s.Module+".rs"), "sqlite", map[string]any{"Header": v.Header, "Store": s, "CratePath": v.CratePath})
			},
		)
	}

	for _, c := range v.Controllers {
		c := c

		steps = append(steps, func() error {
			return add(path.Join(root, "controller", "zz_generated_"+c.Snake+"_controller.rs"), "controller", map[string]any{"Header": v.Header, "Controller": c, "CratePath": v.CratePath})
		})
	}

	for _, layer := range Layers {
		layer := layer

		mod := layerMod{
			Header:   v.Header,
			Allow:    allowingLayers[layer],
			Entries:  entries[layer],
			UserMods: userMods[layer],
		}
		sort.Slice(mod.Entries, func(i, j int) bool { return mod.Entries[i].Module < mod.Entries[j].Module })
		sort.Strings(mod.UserMods)

		steps = append(steps, func() error {
			return add(path.Join(root, layer, "mod.rs"), "layer_mod", mod)
		})
	}

	if !opts.Root {
		steps = append(steps, func() error {
			return add("mod.rs", "cell_mod", map[string]any{"Header": v.Header, "Layers": Layers})
		})
	}

	for _, step := range steps {
		if err := step(); err != nil {
			return nil, err
		}
	}

	manifest := BuildManifest(v)
	if opts.Generator != "" {
		manifest.Generator = opts.Generator
	}

	body, err := cellmanifest.Marshal(manifest)
	if err != nil {
		return nil, fmt.Errorf("emitting the rest cell: %w", err)
	}

	files = append(files, File{Path: cellmanifest.FileName, Content: string(body)})

	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })

	return files, nil
}

func BuildManifest(v view) cellmanifest.Manifest {
	m := cellmanifest.Manifest{
		Version:   cellmanifest.Version,
		Cell:      v.Cell,
		Generator: Generator,
	}

	requires := make([]string, 0, len(v.Controllers))

	for _, c := range v.Controllers {
		ports := make([]string, 0, len(c.Ports))
		for _, p := range c.Ports {
			ports = append(ports, p.Port)
		}

		m.Provides.Controllers = append(m.Provides.Controllers, cellmanifest.Controller{
			Trait:  c.Pascal + "Controller",
			Impl:   c.Pascal + "ControllerImpl",
			Module: v.ModulePrefix + "controller",
			Ports:  ports,
		})

		requires = append(requires, c.Pascal+"Controller")
	}

	if len(v.Controllers) > 0 {
		m.Provides.Drivers = append(m.Provides.Drivers, cellmanifest.Driver{
			Name:     v.DriverName,
			Type:     "HttpDriver",
			Module:   v.ModulePrefix + "driver::http_driver",
			Requires: requires,
			Config: map[string]cellmanifest.ConfigField{
				"addr": {
					Type:        cellmanifest.FieldTypeString,
					Default:     DefaultAddress,
					Description: "The host and port the http driver binds",
				},
			},
		})
	}

	for _, s := range v.Stores {
		m.Provides.Ports = append(m.Provides.Ports, cellmanifest.Port{
			Trait:  s.Port,
			Module: v.ModulePrefix + "port::" + s.PortSnake,
		})

		m.Provides.Adapters = append(m.Provides.Adapters, cellmanifest.Adapter{
			Name:       s.AdapterName,
			Type:       s.Struct,
			Module:     v.ModulePrefix + "adapter::" + s.Module,
			Implements: s.Port,
			Config: map[string]cellmanifest.ConfigField{
				"path": {
					Type:        cellmanifest.FieldTypeString,
					Default:     DefaultStorePath,
					Description: "The sqlite file the " + s.Snake + " store opens",
				},
			},
		})
	}

	return m
}

func render(name string, data any) (string, error) {
	var buf bytes.Buffer
	if err := templates.ExecuteTemplate(&buf, name, data); err != nil {
		return "", fmt.Errorf("rendering %s: %w", name, err)
	}

	return buf.String(), nil
}

