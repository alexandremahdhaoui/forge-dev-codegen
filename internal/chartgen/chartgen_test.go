func TestWhenNoDriverCarriesAProtocolThereIsNoServiceFileAndNoPorts(t *testing.T) {
	cells := manifests()
	udp := cells["udp"]
	udp.Provides.Drivers = udp.Provides.Drivers[1:]
	delete(cells, "rest")
	delete(cells, "grpc")

	root := t.TempDir()
	writeFile(t, filepath.Join(root, hexrust.CellConfigFile), strings.Replace(rootForgeDev, "[rest, grpc, udp]", "[udp]", 1))
	writeFile(t, filepath.Join(root, "wiring.yaml"), wiring)
	writeFile(t, filepath.Join(root, "src", "udp", hexrust.CellConfigFile), "name: songe-hello\nkind: udp\n")

	if err := cellmanifest.Write(filepath.Join(root, "src", "udp", cellmanifest.FileName), udp); err != nil {
		t.Fatalf("writing the udp manifest: %v", err)
	}

	files := generate(t, root)

	if _, ok := files[chartgen.ServiceFile]; ok {
		t.Errorf("a service was emitted with no driver listening\n%s", files[chartgen.ServiceFile])
	}

	if strings.Contains(files[chartgen.DeploymentFile], "ports:") {
		t.Errorf("the deployment carries ports with no driver listening\n%s", files[chartgen.DeploymentFile])
	}
}

