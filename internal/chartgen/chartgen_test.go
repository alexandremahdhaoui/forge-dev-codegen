func writeFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("creating %s: %v", filepath.Dir(path), err)
	}

	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("writing %s: %v", path, err)
	}
}

func crate(t *testing.T, cells map[string]cellmanifest.Manifest) string {
	t.Helper()

	root := t.TempDir()
	writeFile(t, filepath.Join(root, hexrust.CellConfigFile), rootForgeDev)
	writeFile(t, filepath.Join(root, "wiring.yaml"), wiring)
	writeFile(t, filepath.Join(root, "chart", "forge-dev.yaml"), "name: songe-hello\nkind: chart\n")

	for cell, m := range cells {
		writeFile(t, filepath.Join(root, "src", cell, hexrust.CellConfigFile), "name: songe-hello\nkind: "+cell+"\n")

		if err := cellmanifest.Write(filepath.Join(root, "src", cell, cellmanifest.FileName), m); err != nil {
			t.Fatalf("writing the %s manifest: %v", cell, err)
		}
	}

	return root
}

func generate(t *testing.T, root string) map[string]string {
	t.Helper()

	files, err := chartgen.Generate(chartgen.Options{
		OpenapiSpec: []byte(configSpec),
		SrcDir:      filepath.Join(root, "chart"),
	})
	if err != nil {
		t.Fatalf("emitting the chart: %v", err)
	}

	out := map[string]string{}
	for _, f := range files {
		out[f.Path] = f.Content
	}

	return out
}

func generateHello(t *testing.T) map[string]string {
	t.Helper()

	return generate(t, crate(t, manifests()))
}

func TestTheChartCarriesTheRootNameAndItsVersionAsBothChartAndAppVersion(t *testing.T) {
	files := generateHello(t)

	var chart struct {
		APIVersion  string `json:"apiVersion"`
		Name        string `json:"name"`
		Description string `json:"description"`
		Type        string `json:"type"`
		Version     string `json:"version"`
		AppVersion  string `json:"appVersion"`
	}

	if err := yaml.Unmarshal([]byte(files[chartgen.ChartFile]), &chart); err != nil {
		t.Fatalf("reading Chart.yaml: %v\n%s", err, files[chartgen.ChartFile])
	}

	if chart.APIVersion != "v2" || chart.Type != "" {
		t.Errorf("Chart.yaml = %+v", chart)
	}

	if chart.Name != "songe-hello" || chart.Description != "The hello service." {
		t.Errorf("Chart.yaml = %+v", chart)
	}

	if chart.Version != "0.1.0" || chart.AppVersion != "0.1.0" {
		t.Errorf("Chart.yaml = %+v, want version and appVersion both 0.1.0", chart)
	}
}

func TestValuesHoldOneKeyPerSpecPropertyPlusTheImageRepositoryAndNothingElse(t *testing.T) {
	files := generateHello(t)

	var values map[string]any
	if err := yaml.Unmarshal([]byte(files[chartgen.ValuesFile]), &values); err != nil {
		t.Fatalf("reading values.yaml: %v\n%s", err, files[chartgen.ValuesFile])
	}

	want := map[string]any{
		"image":                          map[string]any{"repository": "songe-hello-node"},
		"driver_rest":                    true,
		"greeting_store_memory_capacity": float64(100),
		"greeting_store_sqlite_path":     ":memory:",
		"grpc_addr":                      "127.0.0.1:0",
		"rest_addr":                      "127.0.0.1:0",
		"tick_interval_ms":               float64(1000),
		"ticket_verifier_secret_secret":  "",
		"udp_addr":                       "127.0.0.1:0",
	}

	if len(values) != len(want) {
		t.Fatalf("values.yaml has keys %v, want %v", keys(values), keys(want))
	}

	for key, value := range want {
		if image, ok := value.(map[string]any); ok {
			got, _ := values[key].(map[string]any)
			if got["repository"] != image["repository"] || len(got) != 1 {
				t.Errorf("image = %v, want %v", values[key], image)
			}

			continue
		}

		if values[key] != value {
			t.Errorf("values.%s = %v (%T), want %v (%T)", key, values[key], values[key], value, value)
		}
	}

	if !strings.HasPrefix(strings.SplitN(files[chartgen.ValuesFile], "\n", 2)[1], "image:\n  repository: songe-hello-node\n") {
		t.Errorf("values.yaml does not start with the image block\n%s", files[chartgen.ValuesFile])
	}
}

func keys(m map[string]any) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}

	return out
}

