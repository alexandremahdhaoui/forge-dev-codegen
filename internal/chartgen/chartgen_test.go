func TestTheDeploymentEnvNamesEveryPropertyByItsEnvInSortedOrder(t *testing.T) {
	files := generateHello(t)
	deployment := files[chartgen.DeploymentFile]

	wantInOrder := []string{
		"- name: SONGE_HELLO_NODE_DRIVER_GRPC\n              value: {{ .Values.driver_grpc | quote }}",
		"- name: SONGE_HELLO_NODE_DRIVER_REST\n              value: {{ .Values.driver_rest | quote }}",
		"- name: SONGE_HELLO_NODE_DRIVER_UDP\n              value: {{ .Values.driver_udp | quote }}",
		"- name: SONGE_HELLO_NODE_GREETING_STORE_MEMORY_CAPACITY\n              value: {{ .Values.greeting_store_memory_capacity | quote }}",
		"- name: SONGE_HELLO_NODE_GREETING_STORE_SQLITE_PATH\n              value: {{ .Values.greeting_store_sqlite_path | quote }}",
		"- name: SONGE_HELLO_NODE_GRPC_ADDR\n              value: {{ .Values.grpc_addr | quote }}",
		"- name: SONGE_HELLO_NODE_REST_ADDR\n              value: {{ .Values.rest_addr | quote }}",
		"- name: SONGE_HELLO_NODE_TICK_INTERVAL_MS\n              value: {{ .Values.tick_interval_ms | quote }}",
		"- name: SONGE_HELLO_NODE_TICKET_VERIFIER\n              value: {{ .Values.ticket_verifier | quote }}",
		secretKeyRef,
		"- name: SONGE_HELLO_NODE_UDP_ADDR\n              value: {{ .Values.udp_addr | quote }}",
		"- name: SONGE_HELLO_NODE_WORLD_CLIENT_ENDPOINT\n              value: {{ " + endpointRequired + " | quote }}",
	}

	last := -1
	for _, want := range wantInOrder {
		at := strings.Index(deployment, want)
		if at < 0 {
			t.Fatalf("the deployment lacks %q\n%s", want, deployment)
		}

		if at < last {
			t.Fatalf("the env entry %q is out of sorted order\n%s", want, deployment)
		}

		last = at
	}

	if strings.Count(deployment, "- name: SONGE_HELLO_NODE_") != len(wantInOrder) {
		t.Errorf("the deployment carries an env entry no property declares\n%s", deployment)
	}

	if !strings.Contains(deployment, "- name: songe-hello-node\n          image: \"{{ .Values.image.repository }}:{{ .Chart.AppVersion }}\"") {
		t.Errorf("the container is not named after the binary with the chart app version as its tag\n%s", deployment)
	}
}

func TestRestAndGrpcGetTcpPortsUdpGetsAUdpPortAndTickGetsNone(t *testing.T) {
	files := generateHello(t)
	deployment, service := files[chartgen.DeploymentFile], files[chartgen.ServiceFile]

	for _, want := range []string{
		"{{- if .Values.driver_rest }}\n            - name: rest\n              containerPort: " + portRead("rest_addr") + "\n              protocol: TCP\n            {{- end }}",
		"{{- if .Values.driver_grpc }}\n            - name: grpc\n              containerPort: " + portRead("grpc_addr") + "\n              protocol: TCP\n            {{- end }}",
		"{{- if .Values.driver_udp }}\n            - name: udp\n              containerPort: " + portRead("udp_addr") + "\n              protocol: UDP\n            {{- end }}",
	} {
		if !strings.Contains(deployment, want) {
			t.Errorf("the deployment lacks %q\n%s", want, deployment)
		}
	}

	for _, want := range []string{
		"{{- if or (.Values.driver_rest) (.Values.driver_grpc) (.Values.driver_udp) }}\napiVersion: v1",
		"{{- if .Values.driver_rest }}\n    - name: rest\n      protocol: TCP\n      port: " + portRead("rest_addr") + "\n      targetPort: " + portRead("rest_addr") + "\n    {{- end }}",
		"{{- if .Values.driver_grpc }}\n    - name: grpc\n      protocol: TCP\n      port: " + portRead("grpc_addr"),
		"{{- if .Values.driver_udp }}\n    - name: udp\n      protocol: UDP\n      port: " + portRead("udp_addr"),
	} {
		if !strings.Contains(service, want) {
			t.Errorf("the service lacks %q\n%s", want, service)
		}
	}

	if strings.Contains(deployment, "name: tick\n") || strings.Contains(service, "name: tick\n") {
		t.Errorf("the tick driver got a port and it listens on nothing\n%s\n%s", deployment, service)
	}

	if strings.Count(deployment, "containerPort:") != 3 || strings.Count(service, "targetPort:") != 3 {
		t.Errorf("want exactly three ports\n%s\n%s", deployment, service)
	}
}

